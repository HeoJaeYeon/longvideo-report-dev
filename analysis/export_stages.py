"""
Export every intermediate output of finished reports as readable files, one folder per report (read-only, CPU, 2026-10-26).

Sources (nothing is regenerated by an LLM):
  - Deep-Reporter session log (<run>/dr_logs_s<i>/*.jsonl): full planner / query / writer prompts and raw outputs
  - report.json: parsed outline, queries, retrieved evidence (full), section bodies after repeated-sentence removal
  - validation.json: repetition, start/end claim findings, rule-check findings, image-time alignment
  - LLM server log (llm_server_s<i>_*.log): tokens / finish reason / seconds per call (order: planner, then
    query, L1 filter, writer per section)
  - retrieval service log (service_s<i>_*.log): per-request candidates, filter mode, counts, seconds
  - grounded section bodies: grounding_postprocessor.ground_report re-run on report.json into a temporary folder;
    the result is checked against report.md (must match after the header)
Output: internal/inspect/<run>/<job>/
  README.md                     index + per-call table
  01_planner_prompt.md          full planner prompt (with the video overview)
  02_planner_output.md          raw planner output + parsed outline
  sNN/1_query_prompt.md         full query-generation prompt
  sNN/2_query_output.md         raw output + parsed text/image queries
  sNN/3_retrieval.md            service request log + every text/image evidence item (cited or not)
  sNN/4_writer_prompt.md        full writer prompt (evidence as the writer saw it)
  sNN/5_writer_output_raw.md    raw writer output (before any post-processing)
  sNN/6_postprocess.md          repeated-sentence removal, start/end claim check, rule check, image-time alignment,
                                and the grounded body exactly as it appears in report.md
  and internal/inspect/<run>/COMPARE_<video>.md: outline, queries and evidence of r1-r3 side by side
Usage: python analysis/export_stages.py [--run outputs/p9p19_check_20261025_141401]
"""
import argparse, ast, glob, json, os, re, shutil, sys, tempfile

RF = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, RF)
import grounding_postprocessor as G


def fence(text, lang=""):
    ticks = "````" if "```" in text else "```"
    return f"{ticks}{lang}\n{text}\n{ticks}"


def load_jobs(run):
    jobs = {}
    for line in open(os.path.join(run, "batch.out")):
        if line.startswith("[report]"):
            d = ast.literal_eval(line[len("[report] "):].strip())
            jobs[d["job"]] = d
    return jobs


def log_lines(path, pattern, t0, t1):
    out = []
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(pattern, line)
        if m and t0 <= m.group(1).replace(" ", "T") <= t1:
            out.append(m)
    return out


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text.rstrip() + "\n")


def cited_txt(content):
    return sorted({i for g in G.CITE_GROUP_RE.findall(content) for k, i in G.parse_tokens(g)[0] if k == "txt"})


def cited_img(content):
    s = {int(i) for i in G.IMG_EMBED_RE.findall(content)}
    s |= {i for g in G.CITE_GROUP_RE.findall(content) for k, i in G.parse_tokens(g)[0] if k == "img"}
    return sorted(s)


def export_job(run, job, meta, sessions, out_root):
    rdir = os.path.join(run, job)
    rj = json.load(open(os.path.join(rdir, "report.json")))
    vj = json.load(open(os.path.join(rdir, "validation.json")))
    ses = sessions[rj["session_id"]]
    t0, t1 = ses["start_time"][:19], ses["end_time"][:19]
    stack = meta["stack"]
    llm = log_lines(glob.glob(os.path.join(run, f"llm_server_s{stack}_gpu*.log"))[0],
                    r"(\S+ \S+),\d+ local_llm_server INFO chat\.completions: prompt=(\d+) completion=(\d+) finish=(\w+) ([\d.]+)s",
                    t0, t1)
    svc = log_lines(glob.glob(os.path.join(run, f"service_s{stack}_gpu*.log"))[0],
                    r"(\S+ \S+),\d+ videorag_retriever INFO search (\w+): (.*)", t0, t1)
    outline = rj["outline"]
    n = len(outline)
    assert len(llm) == 1 + 3 * n, f"{job}: {len(llm)} LLM calls in the server log window, expected {1 + 3 * n}"
    assert len(svc) == 2 * n, f"{job}: {len(svc)} search requests in the service log window, expected {2 * n}"
    calls = ses["llm_calls"]
    q_calls = [c for c in calls if c["call_type"] == "query_generation"]
    w_calls = [c for c in calls if c["call_type"] == "section_writing"]
    assert calls[0]["call_type"] == "outline_generation" and len(q_calls) == n and len(w_calls) == n

    # grounded bodies: re-run the post-processor on report.json and check it reproduces report.md
    tmp = tempfile.mkdtemp(prefix="export_stages_")
    try:
        grounded = G.ground_report({"outline": outline}, False, tmp, header=None)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    report_md = open(os.path.join(rdir, "report.md"), encoding="utf-8").read()
    body_md = report_md.split("\n\n", 1)[1] if report_md.startswith(">") else report_md
    reproduced = grounded["markdown"] == body_md
    assert reproduced, f"{job}: re-run of ground_report does not reproduce report.md"

    out = os.path.join(out_root, job)
    rel = lambda p: os.path.relpath(p, RF)
    # planner
    pc = calls[0]
    write(os.path.join(out, "01_planner_prompt.md"),
          f"# Planner prompt — {job}\n\n- Source: `{rel(glob.glob(os.path.join(run, f'dr_logs_s{stack}', '*.jsonl'))[0])}` "
          f"session `{rj['session_id']}`, llm_calls[0] (`outline_generation`)\n"
          f"- Length: {len(pc['input_messages'][0]['content']):,} chars, {llm[0].group(2)} tokens (LLM server log)\n\n"
          + fence(pc["input_messages"][0]["content"]))
    parsed = "\n".join(f"### Section {i}\n\n**section_description**: {s['section_description']}\n\n**sectional_checklist**:\n"
                       + "\n".join(f"- {c}" for c in s["sectional_checklist"]) for i, s in enumerate(outline, 1))
    write(os.path.join(out, "02_planner_output.md"),
          f"# Planner output — {job}\n\n- {llm[0].group(3)} output tokens, finish={llm[0].group(4)}, {llm[0].group(5)} s\n\n"
          f"## Raw output (as returned by the LLM)\n\n{fence(pc['output_content'])}\n\n## Parsed outline ({n} sections)\n\n{parsed}")

    rows = [f"| planner | — | {llm[0].group(2)} | {llm[0].group(3)} | {llm[0].group(4)} | {llm[0].group(5)} |"]
    index = []
    for i, s in enumerate(outline, 1):
        sd = os.path.join(out, f"s{i:02d}")
        q, f_, w = llm[1 + 3 * (i - 1)], llm[2 + 3 * (i - 1)], llm[3 + 3 * (i - 1)]
        rows += [f"| query | {i} | {q.group(2)} | {q.group(3)} | {q.group(4)} | {q.group(5)} |",
                 f"| L1 filter (in search) | {i} | {f_.group(2)} | {f_.group(3)} | {f_.group(4)} | {f_.group(5)} |",
                 f"| writer | {i} | {w.group(2)} | {w.group(3)} | {w.group(4)} | {w.group(5)} |"]
        qc, wc = q_calls[i - 1], w_calls[i - 1]
        write(os.path.join(sd, "1_query_prompt.md"),
              f"# Section {i} — query-generation prompt\n\n- {q.group(2)} prompt tokens\n\n" + fence(qc["input_messages"][0]["content"]))
        write(os.path.join(sd, "2_query_output.md"),
              f"# Section {i} — query-generation output\n\n- {q.group(3)} output tokens, finish={q.group(4)}, {q.group(5)} s\n\n"
              f"## Raw output\n\n{fence(qc['output_content'])}\n\n## Parsed (used for retrieval)\n\n**text_queries**\n"
              + "\n".join(f"{k}. `{x}`" for k, x in enumerate(s["text_queries"] or [], 1))
              + "\n\n**image_queries**\n" + "\n".join(f"{k}. `{x}`" for k, x in enumerate(s["image_queries"] or [], 1)))
        texts, imgs = s["retrieved_texts"] or [], s["retrieved_images"] or []
        ct, ci = set(cited_txt(s["content"] or "")), set(cited_img(s["content"] or ""))
        st, si = svc[2 * (i - 1)], svc[2 * (i - 1) + 1]
        lines = [f"# Section {i} — retrieval results",
                 "", "## Requests (retrieval service log)", "",
                 f"- text  request ({st.group(1)}): `{st.group(3)}`",
                 f"- image request ({si.group(1)}): `{si.group(3)}`",
                 f"- L1 filter LLM call: prompt {f_.group(2)} tokens, output {f_.group(3)} tokens, {f_.group(5)} s "
                 "(its input candidates and raw output are not logged)",
                 "", f"## Text evidence ({len(texts)} items, in the order the writer saw them as txt1..txt{len(texts)})", "",
                 "| txt | cited | source | granularity | time | rank / score | uid |", "|---|---|---|---|---|---|---|"]
        for k, t in enumerate(texts, 1):
            tm = (f"{G.hms_from_time_str(t.get('start_time'))}–{G.hms_from_time_str(t.get('end_time'))}"
                  if t.get("start_time") else "no timestamp")
            lines.append(f"| txt{k} | {'✓' if k in ct else ''} | {t.get('source')} | {t.get('granularity') or '—'} | {tm} | "
                         f"{t.get('rank')} / {t.get('score')} ({t.get('score_type')}) | `{t.get('uid')}` |")
        lines += ["", "### Full text of each item (`content` field, exactly what the writer received)", ""]
        for k, t in enumerate(texts, 1):
            lines += [f"**txt{k}**{' (cited)' if k in ct else ''}", "", fence(t.get("content", "")), ""]
        lines += [f"## Image evidence ({len(imgs)} items, img1..img{len(imgs)})", "",
                  "| img | cited | frame | clip | uid | file |", "|---|---|---|---|---|---|"]
        for k, m in enumerate(imgs, 1):
            lines.append(f"| img{k} | {'✓' if k in ci else ''} | {G.hms(m.get('frame_sec'))} | "
                         f"{G.hms_from_time_str(m.get('start_time'))}–{G.hms_from_time_str(m.get('end_time'))} | `{m.get('uid')}` | "
                         f"`{rel(m['img_path']) if m.get('img_path', '').startswith(RF) else m.get('img_path')}` |")
        lines += ["", "### Caption of each image (what the writer received instead of the picture)", ""]
        for k, m in enumerate(imgs, 1):
            lines += [f"**img{k}**{' (cited)' if k in ci else ''}", "", fence(m.get("caption", "")), ""]
        write(os.path.join(sd, "3_retrieval.md"), "\n".join(lines))
        write(os.path.join(sd, "4_writer_prompt.md"),
              f"# Section {i} — writer prompt\n\n- {w.group(2)} prompt tokens\n\n" + fence(wc["input_messages"][0]["content"]))
        write(os.path.join(sd, "5_writer_output_raw.md"),
              f"# Section {i} — writer output (raw)\n\n- {w.group(3)} output tokens, finish={w.group(4)}, {w.group(5)} s "
              f"({'cut at the server max_tokens cap' if w.group(4) == 'length' else 'normal end'})\n\n" + fence(wc["output_content"]))
        rep = next((r for r in vj["repetition"] if r["index"] == i), None)
        bnd = [b for b in vj["boundary_findings"] if b["section"] == i]
        gf = [g for g in vj["grounding_findings"] if g["section"] == i]
        vs = next(x for x in vj["sections"] if x["index"] == i)
        refs_used = sorted({int(n_) for n_ in re.findall(r"\[(\d+)\]", grounded["section_bodies"][i - 1])})
        ref_lines = [r["line"] for r in grounded["references"] if r["n"] in refs_used]
        pp = [f"# Section {i} — post-processing", "",
              "## 1. Repeated-sentence removal (`dedupe_repeated_sentences`)", "",
              f"- removed sentences: {rep['removed_sentences']}, a sentence occurred up to {rep['max_repeat']} times, "
              f"ends mid-sentence: {rep['ends_mid_sentence']}",
              f"- raw writer output {len(wc['output_content'].split())} words → after removal {len((s['content'] or '').split())} words", "",
              "## 2. Start/end claim check (`boundary_claims`)", ""]
        pp += [f"- {b['status']}: {b['sentence']} (cited {b.get('cited')}"
               + (f", latest cited end {b['latest_cited_end']}" if b.get("latest_cited_end") else "") + ")" for b in bnd] or ["- none"]
        pp += ["", "## 3. Rule-based evidence check (`check_section_grounding`)", "",
               f"- stats: `{json.dumps(vs['grounding_stats'])}`", ""]
        pp += [f"- **{g['status']}** {g.get('kind', '')} `{g.get('token', g.get('tokens', ''))}` cited {g.get('cited')}"
               + (f" found in {g['found_in_uncited']}" if g.get("found_in_uncited") else "") + f" — {g['sentence']}" for g in gf] or ["- no findings"]
        pp += ["", "## 4. Citation conversion stats", "", f"- `{json.dumps(vs['citations'])}`",
               f"- text evidence not cited in this section: {vs['unused_text_evidence']} of {len(texts)}", "",
               "## 5. Image-text time alignment", ""]
        pp += [f"- {a['img']} frame {a['frame']}: gap to text cited in the same paragraph {a['gap_to_local_text_sec']} s "
               f"(ranges {a['local_text_ranges']}), to any text cited in the section {a['gap_to_section_text_sec']} s"
               for a in vs["image_time_alignment"]] or ["- no cited image"]
        pp += ["", "## 6. Section body after removal (input to the conversion, still with txtN/imgN)", "", fence(s["content"] or ""),
               "", "## 7. Grounded body (exactly as in report.md)", "", fence(grounded["section_bodies"][i - 1]),
               "", "## 8. References used by this section (global numbers)", "", fence("\n".join(ref_lines))]
        write(os.path.join(sd, "6_postprocess.md"), "\n".join(pp))
        index.append(f"| {i} | {(s['section_description'] or '')[:80]}… | {len(s['text_queries'] or [])} / {len(s['image_queries'] or [])} | "
                     f"{len(texts)} / {len(imgs)} | {len(ct)} / {len(ci)} | {w.group(3)} ({w.group(4)}) | `s{i:02d}/` |")

    readme = [f"# {job} — intermediate outputs", "",
              f"- Run `{rel(run)}`, stack {stack} (GPU {meta['gpu']}), session `{rj['session_id']}` {t0} – {t1} (UTC)",
              f"- Query: {rj['query']}", f"- Checklist: {rj['checklist']}",
              f"- validation: {vj['status']}, generation {vj['timings']['generation_sec']} s",
              f"- report.md reproduced from report.json by re-running ground_report: {reproduced}", "",
              "## Files", "", "- `01_planner_prompt.md`, `02_planner_output.md`",
              "- `sNN/1_query_prompt.md` … `sNN/6_postprocess.md` (see the table)", "",
              "| section | description | text / image queries | text / image evidence | cited text / image | writer output tokens | folder |",
              "|---|---|---|---|---|---|---|"] + index + [
              "", "## LLM calls (LLM server log, in call order)", "",
              "| call | section | prompt tokens | output tokens | finish | seconds |", "|---|---|---|---|---|---|"] + rows + [
              "", "## Validation warnings", ""] + [f"- {x}" for x in vj["warnings"]]
    write(os.path.join(out, "README.md"), "\n".join(readme))
    return rj


def compare(out_root, video, reps):
    lines = [f"# {video} — r1 / r2 / r3 side by side", "", "Same video, same settings; differences come from sampling.", ""]
    for r, rj in reps:
        lines += [f"## r{r}", ""]
        for i, s in enumerate(rj["outline"], 1):
            title = next((ln.lstrip("#").strip() for ln in (s["content"] or "").split("\n") if ln.startswith("#")), "")
            texts = s["retrieved_texts"] or []
            ct = set(cited_txt(s["content"] or ""))
            ev = ", ".join(f"{'**' if k in ct else ''}{t.get('granularity') or 'sem'} "
                           f"{G.hms_from_time_str(t.get('start_time')) if t.get('start_time') else '—'}{'**' if k in ct else ''}"
                           for k, t in enumerate(texts, 1))
            lines += [f"### S{i}: {title}", "", f"- description: {s['section_description']}",
                      "- checklist: " + " / ".join(s["sectional_checklist"]),
                      "- text queries: " + " / ".join(f"`{x}`" for x in s["text_queries"] or []),
                      "- image queries: " + " / ".join(f"`{x}`" for x in s["image_queries"] or []),
                      f"- text evidence (bold = cited): {ev}", ""]
    write(os.path.join(out_root, f"COMPARE_{video}.md"), "\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default=os.path.join(RF, "outputs", "p9p19_check_20261025_141401"))
    a = ap.parse_args()
    run = os.path.abspath(a.run)
    out_root = os.path.join(RF, "internal", "inspect", os.path.basename(run))
    jobs = load_jobs(run)
    sessions = {}
    for p in glob.glob(os.path.join(run, "dr_logs_s*", "*.jsonl")):
        for line in open(p):
            d = json.loads(line)
            sessions[d["session_id"]] = d
    by_video = {}
    for job in sorted(jobs):
        rj = export_job(run, job, jobs[job], sessions, out_root)
        by_video.setdefault(rj["video_id"], []).append((jobs[job]["repeat"], rj))
        print("exported", job)
    for v, reps in by_video.items():
        compare(out_root, v, sorted(reps, key=lambda x: x[0]))
    print("output:", out_root)


if __name__ == "__main__":
    main()
